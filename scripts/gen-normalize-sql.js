const fs = require("fs");
const path = require("path");

const schema = fs.readFileSync(path.join(__dirname, "..", "prisma", "schema.prisma"), "utf8");
const lines = schema.split("\n");
let model = null;
const map = {};
const modelRe = /^model\s+(\w+)/;
const tblRe = /@@map\("([^"]+)"\)/;
const colRe = /^\s*(\w+)\s+DateTime\??/;

for (const ln of lines) {
  const m = ln.match(modelRe);
  if (m) { model = m[1]; map[model] = { map: null, cols: [] }; continue; }
  if (model) {
    const t = ln.match(tblRe);
    if (t) map[model].map = t[1];
    const c = ln.match(colRe);
    if (c) map[model].cols.push(c[1]);
    if (/^\}/.test(ln)) model = null;
  }
}

let sql = "-- Normalize all DateTime columns to integer epoch-millis (matches Prisma 6.11 SQLite writer).\n-- Idempotent: rows already INTEGER are untouched. Generated by scripts/gen-normalize-sql.js\n";
let n = 0;
for (const [mdl, info] of Object.entries(map)) {
  const table = info.map || mdl;
  for (const c of info.cols) {
    n++;
    sql += 'UPDATE "' + table + '" SET "' + c + '" = CAST(CASE' +
      ' WHEN typeof("' + c + '")="integer" THEN "' + c + '"' +
      ' WHEN typeof("' + c + '")="real" THEN CAST("' + c + '" AS INTEGER)' +
      ' WHEN typeof("' + c + '")="text" AND "' + c + '" NOT GLOB "*-*" THEN CAST("' + c + '" AS INTEGER)' +
      ' ELSE CAST(strftime("%s","' + c + '") AS INTEGER)*1000 + CAST(substr("' + c + '",21,3) AS INTEGER)' +
      ' END AS INTEGER) WHERE "' + c + '" IS NOT NULL AND typeof("' + c + '")!="integer";\n';
  }
}
fs.writeFileSync(path.join(__dirname, "normalize-datetimes-int.sql"), sql);
console.log("columns:", n, "tables:", Object.keys(map).length);
